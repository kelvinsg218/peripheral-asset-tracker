using PeripheralAssetTracker.Application.Discovery;
using PeripheralAssetTracker.Application.Fingerprinting;
using PeripheralAssetTracker.Domain.Enums;
using PeripheralAssetTracker.Infrastructure.Discovery;
using PeripheralAssetTracker.Tests.TestSupport;

namespace PeripheralAssetTracker.Tests.Discovery;

/// <summary>
/// Grouping tests. "real-laptop-usb-headset.json" was captured READ-ONLY from the development
/// laptop (Windows 11) and anonymized (serial/hostname); "synthetic-office-desk.json" is synthetic.
/// </summary>
public class HidDeviceGrouperTests
{
    private static DeviceDiscoveryResult Real() =>
        HidDeviceGrouper.Group(DeviceFixtures.LoadSnapshot("real-laptop-usb-headset.json").Nodes);

    private static DeviceDiscoveryResult Synthetic() =>
        HidDeviceGrouper.Group(DeviceFixtures.LoadSnapshot("synthetic-office-desk.json").Nodes);

    [Fact]
    public void Real_snapshot_seven_hid_entries_become_three_physical_devices()
    {
        var result = Real();

        Assert.Equal(7, result.RawEntryCount);
        Assert.Equal(3, result.Devices.Count);
    }

    [Fact]
    public void Real_usb_headset_two_hid_interfaces_are_one_device_with_serial_from_parent_instance_id()
    {
        var headset = Assert.Single(Real().Devices, d => d.VendorId == "05AC");

        Assert.Equal("EarPods", headset.DeviceName);            // USB product string, not the localized Windows name
        Assert.Equal("Apple", headset.Manufacturer);            // from VID, not "(Dispositivos padrão do sistema)"
        Assert.Equal("110B", headset.ProductId);
        Assert.Equal("TESTSERIAL01", headset.SerialNumber);
        Assert.Equal(@"USB\VID_05AC&PID_110B\TESTSERIAL01", headset.PnpDeviceId);
        Assert.Equal(2, headset.InterfaceInstanceIds.Count);    // MI_03 consumer control + MI_04 vendor defined
        Assert.Equal(DeviceType.Other, headset.SuggestedType);
        Assert.Equal(BusType.Usb, headset.BusType);
        Assert.False(headset.IsBuiltIn);
        Assert.Equal(FingerprintConfidence.High, new DeviceFingerprintService().Compute(headset).Confidence);
    }

    [Fact]
    public void Real_touchpad_four_collections_are_one_builtin_mouse()
    {
        var touchpad = Assert.Single(Real().Devices, d => d.PnpDeviceId == @"ACPI\ELAN06FA\4");

        Assert.Equal(DeviceType.Mouse, touchpad.SuggestedType);
        Assert.Equal(4, touchpad.InterfaceInstanceIds.Count);
        Assert.True(touchpad.IsBuiltIn);
        Assert.Equal(BusType.Internal, touchpad.BusType);
        Assert.Contains(touchpad.Notes, n => n.Contains("touchpad"));
        Assert.Equal(FingerprintConfidence.Low, new DeviceFingerprintService().Compute(touchpad).Confidence);
    }

    [Fact]
    public void Real_ps2_keyboard_is_builtin_low_confidence_without_invented_data()
    {
        var keyboard = Assert.Single(Real().Devices, d => d.SuggestedType == DeviceType.Keyboard);

        Assert.True(keyboard.IsBuiltIn);
        Assert.Null(keyboard.VendorId);
        Assert.Null(keyboard.ProductId);
        Assert.Null(keyboard.SerialNumber);
        Assert.Null(keyboard.Manufacturer); // "(teclados padrões)" is a driver label, not a manufacturer
        Assert.Contains(keyboard.Notes, n => n.Contains("PS/2"));
    }

    [Fact]
    public void Gaming_mouse_with_keyboard_interface_is_one_mouse_with_a_note()
    {
        var g203 = Assert.Single(Synthetic().Devices, d => d.ProductId == "C084");

        Assert.Equal(DeviceType.Mouse, g203.SuggestedType); // interface 0 is the mouse
        Assert.Equal("G203 LIGHTSYNC Gaming Mouse", g203.DeviceName);
        Assert.Equal("ABC123", g203.SerialNumber);
        Assert.Equal(4, g203.InterfaceInstanceIds.Count);
        Assert.Contains("Keyboard", g203.Functions);
        Assert.Contains(g203.Notes, n => n.Contains("mouse E teclado"));
    }

    [Fact]
    public void Keyboard_without_serial_is_detected_with_note()
    {
        var kb = Assert.Single(Synthetic().Devices, d => d.ProductId == "2113");

        Assert.Equal(DeviceType.Keyboard, kb.SuggestedType);
        Assert.Equal("Dell", kb.Manufacturer);
        Assert.Null(kb.SerialNumber); // "5&1A2B3C4D&0&2" is generated by Windows, not a serial
        Assert.Equal(3, kb.InterfaceInstanceIds.Count);
        Assert.Contains(kb.Notes, n => n.Contains("Sem número de série"));
    }

    [Fact]
    public void Two_identical_mice_stay_two_devices_but_share_the_same_fingerprint()
    {
        var mice = Synthetic().Devices.Where(d => d.ProductId == "301A").ToList();

        Assert.Equal(2, mice.Count);
        var service = new DeviceFingerprintService();
        Assert.Equal(service.Compute(mice[0]).Fingerprint, service.Compute(mice[1]).Fingerprint);
        Assert.All(mice, m => Assert.Equal(FingerprintConfidence.Low, service.Compute(m).Confidence));
    }

    [Fact]
    public void Wireless_combo_receiver_is_flagged()
    {
        var receiver = Assert.Single(Synthetic().Devices, d => d.ProductId == "C52B");

        Assert.Equal(DeviceType.Keyboard, receiver.SuggestedType); // MI_00 is the keyboard on Unifying receivers
        Assert.Contains(receiver.Notes, n => n.Contains("receptor"));
        Assert.Contains(receiver.Notes, n => n.Contains("mouse E teclado"));
        Assert.Equal(3, receiver.InterfaceInstanceIds.Count);
    }

    [Fact]
    public void Classic_bluetooth_mouse_is_identified_by_address()
    {
        var mouse = Assert.Single(Synthetic().Devices, d => d.BusType == BusType.Bluetooth);

        Assert.Equal("046D", mouse.VendorId);
        Assert.Equal("B016", mouse.ProductId);
        Assert.Equal("E1C2D3A4B5C6", mouse.BluetoothAddress);
        Assert.Equal("MX Anywhere 2", mouse.DeviceName);
        Assert.Equal(FingerprintConfidence.High, new DeviceFingerprintService().Compute(mouse).Confidence);
    }

    [Fact]
    public void Bluetooth_le_keyboard_is_medium_confidence()
    {
        var keyboard = Assert.Single(Synthetic().Devices, d => d.BusType == BusType.BluetoothLowEnergy);

        Assert.Equal(DeviceType.Keyboard, keyboard.SuggestedType);
        Assert.Equal("046D", keyboard.VendorId);
        Assert.Equal("B35B", keyboard.ProductId);
        Assert.Equal("D1E2F3A4B5C6", keyboard.BluetoothAddress);
        Assert.Equal(FingerprintConfidence.Medium, new DeviceFingerprintService().Compute(keyboard).Confidence);
    }

    [Fact]
    public void Generic_serial_is_medium_confidence()
    {
        var keyboard = Assert.Single(Synthetic().Devices, d => d.VendorId == "1A2C");

        Assert.Equal("0000000000", keyboard.SerialNumber);
        Assert.Equal(FingerprintConfidence.Medium, new DeviceFingerprintService().Compute(keyboard).Confidence);
    }

    [Fact]
    public void Remote_desktop_virtual_devices_are_ignored()
    {
        var result = Synthetic();

        Assert.Equal(2, result.IgnoredVirtualEntryCount);
        Assert.DoesNotContain(result.Devices, d => d.PnpDeviceId!.Contains("RDP") || d.PnpDeviceId.Contains("TERMINPUT"));
    }

    [Fact]
    public void Synthetic_snapshot_yields_expected_device_count() =>
        Assert.Equal(8, Synthetic().Devices.Count);

    [Theory]
    [InlineData(@"USB\VID_046D&PID_C084\ABC123", "ABC123")]
    [InlineData(@"USB\VID_046D&PID_C084\5&1A2B3C4D&0&2", null)]
    [InlineData(@"USB\VID_046D&PID_C084&MI_00\6&1&0&0000", null)]
    [InlineData(@"HID\VID_046D&PID_C084\ABC123", null)]
    [InlineData(@"USB\ROOT_HUB30\5&AAAA&0&0", null)]
    public void Usb_serial_is_only_taken_from_a_usb_device_instance_id(string instanceId, string? expected) =>
        Assert.Equal(expected, HidDeviceGrouper.UsbSerialFromInstanceId(instanceId));

    [Theory]
    [InlineData(@"USB\VID_046D&PID_C084\X", "046D", "C084")]
    [InlineData(@"BTHENUM\{00001124-0000-1000-8000-00805F9B34FB}_VID&0002046D_PID&B016\7&1&0&E1C2D3A4B5C6_C00000000", "046D", "B016")]
    [InlineData(@"BTHLEDEVICE\{00001812-0000-1000-8000-00805F9B34FB}_DEV_VID&02046D_PID&B35B_REV&0012_D1E2F3A4B5C6\8&1", "046D", "B35B")]
    [InlineData(@"HID\VID_04F3&UP:000D_U:000E", "04F3", null)]
    public void Vendor_and_product_ids_are_parsed_from_usb_and_bluetooth_ids(string id, string? vid, string? pid)
    {
        Assert.Equal(vid, HidDeviceGrouper.ParseVendorId(id));
        Assert.Equal(pid, HidDeviceGrouper.ParseProductId(id));
    }

    [Fact]
    public void Missing_parent_nodes_do_not_break_grouping()
    {
        var orphan = new PnpNode
        {
            InstanceId = @"HID\VID_046D&PID_C077\7&ORPHAN&0&0000",
            ParentInstanceId = @"USB\VID_046D&PID_C077\NOT_CAPTURED",
            ClassName = "Mouse",
            EnumeratorName = "HID",
            HardwareIds = ["HID_DEVICE_SYSTEM_MOUSE"]
        };

        var device = Assert.Single(HidDeviceGrouper.Group([orphan]).Devices);

        Assert.Equal(DeviceType.Mouse, device.SuggestedType);
        Assert.Equal("046D", device.VendorId);
        Assert.Equal("C077", device.ProductId);
        Assert.Null(device.SerialNumber);
    }
}
